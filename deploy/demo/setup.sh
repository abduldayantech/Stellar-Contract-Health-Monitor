#!/usr/bin/env bash
# Sets up (or updates) the public testnet demo on a fresh Ubuntu 22.04/24.04 server.
#
#   curl -fsSL https://raw.githubusercontent.com/abduldayantech/Stellar-Contract-Health-Monitor/main/deploy/demo/setup.sh | sudo bash
#   # or, with your own domain pointing at the server:
#   curl -fsSL .../setup.sh | sudo DEMO_DOMAIN=demo.example.com bash
#
# Re-running it pulls the latest main and rebuilds. Secrets are generated once and kept in
# /opt/stellar-health/.env.
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/abduldayantech/Stellar-Contract-Health-Monitor.git}"
BRANCH="${BRANCH:-main}"
DIR="${DIR:-/opt/stellar-health}"

if [ "$(id -u)" -ne 0 ]; then
  echo "Run as root (sudo)." >&2
  exit 1
fi

log() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }

log "Installing Docker and git"
if ! command -v docker >/dev/null; then
  curl -fsSL https://get.docker.com | sh
fi
command -v git >/dev/null || (apt-get update -qq && apt-get install -y -qq git)

# Building the dashboard needs more memory than the smallest servers have.
if [ ! -f /swapfile ] && [ "$(awk '/MemTotal/ {print $2}' /proc/meminfo)" -lt 4000000 ]; then
  log "Adding 2 GB swap"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  echo '/swapfile none swap sw 0 0' >>/etc/fstab
fi

if command -v ufw >/dev/null && ufw status | grep -q active; then
  ufw allow 80/tcp >/dev/null && ufw allow 443 >/dev/null
fi

log "Fetching $BRANCH"
if [ -d "$DIR/.git" ]; then
  git -C "$DIR" fetch -q origin "$BRANCH" && git -C "$DIR" reset -q --hard "origin/$BRANCH"
else
  git clone -q --branch "$BRANCH" "$REPO_URL" "$DIR"
fi
cd "$DIR"

if [ ! -f .env ]; then
  log "Generating secrets in $DIR/.env"
  ip="$(curl -fsS4 https://api.ipify.org)"
  cat >.env <<EOF
# Generated by deploy/demo/setup.sh on $(date -u +%F)
DEMO_DOMAIN=${DEMO_DOMAIN:-$ip.sslip.io}
ADMIN_API_TOKEN=$(openssl rand -hex 32)
SECRETS_ENCRYPTION_KEY=$(openssl rand -base64 32)
POSTGRES_PASSWORD=$(openssl rand -hex 24)
TESTNET_RPC_URL=https://soroban-testnet.stellar.org
EOF
  chmod 600 .env
elif [ -n "${DEMO_DOMAIN:-}" ]; then
  sed -i "s/^DEMO_DOMAIN=.*/DEMO_DOMAIN=$DEMO_DOMAIN/" .env
fi

compose() { docker compose -f docker-compose.yml -f deploy/demo/docker-compose.demo.yml "$@"; }

log "Building and starting (the first build takes several minutes)"
compose up -d --build --remove-orphans

log "Seeding demo contracts, rules and the public viewer token"
compose --profile seed run --rm seed

domain="$(grep '^DEMO_DOMAIN=' .env | cut -d= -f2)"
log "Done"
echo "Dashboard:   https://$domain"
echo "Admin token: in $DIR/.env (ADMIN_API_TOKEN) – keep it private"
echo "Logs:        cd $DIR && docker compose -f docker-compose.yml -f deploy/demo/docker-compose.demo.yml logs -f"
